# LGA-only Lagos report; external locations are supplied by the caller.
build_lagos_aggregate <- function(root, join_dir, cache_dir, work_dir, python="python3", input_zip="") {
 root<-normalizePath(root,mustWork=TRUE)
 source(file.path(root,"administrative_area/analysis/report_pipeline.R"),local=TRUE)
 use_project_library(root)
 if(nzchar(join_dir))join_dir<-project_path(join_dir,root);cache_dir<-project_path(cache_dir,root);work_dir<-project_path(work_dir,root)
 context<-prepare_aggregate_inputs(root,input_zip,work_dir,cache_dir,join_dir)
 join_dir<-context$join_dir;cache_dir<-context$cache_dir
 module<-file.path(root,"administrative_area/analysis/lagos")
 data<-file.path(work_dir,"Lagos_analysis_aggregate_files");dir.create(data,recursive=TRUE,showWarnings=FALSE)
 input<-file.path(join_dir,"checked_geography/lagos_women_manitoba.rds")
 facilities<-file.path(join_dir,"audit/facility_linkage_inputs.rds")
 if(!all(file.exists(c(input,facilities))))stop("Supply a verified administrative join directory with checked geography and facility audit inputs")
 hashes<-unname(tools::md5sum(c(input,facilities)))
 stage<-function(name,args)run_stage(file.path(module,name),args,python)
 build<-c("--input",input,"--facility-input",facilities)
 stage("build_analysis.R",c(build,"--output-dir",data))
 stage("fit_models.R",c("--data-dir",data,"--output-dir",file.path(data,"models_zscore")))
 pca<-file.path(data,"pca_appendix")
 stage("build_pca_scores.R",c("--data-dir",data,"--output-dir",pca))
 stage("fit_models.R",c("--data-dir",data,"--output-dir",file.path(pca,"models"),"--score-method","pca","--pca-score-file",file.path(pca,"pca_scores.rds")))
 sensitivity<-file.path(data,"complete_facility_sensitivity")
 stage("build_analysis.R",c(build,"--output-dir",sensitivity,"--facility-sample","complete","--reference-dir",data))
 stage("fit_models.R",c("--data-dir",sensitivity,"--output-dir",file.path(sensitivity,"models_zscore")))
 stage("build_analysis.R",c(build,"--output-dir",file.path(data,"complete_demand_sensitivity"),"--demand-sample","complete","--reference-dir",data))
 stage("verify_analysis.R",c(build,"--data-dir",data))
 native<-file.path(work_dir,"Lagos_analysis_aggregate.html")
 stage("render_analysis.py",c("--data-dir",data,"--reference-html",file.path(root,"analysis/assets/lagos_map_template.html"),"--output",native))
 stage("verify_html.py",c("--data-dir",data,"--html",native))
 fragment<-file.path(work_dir,"report_fragment.html")
 run_stage(file.path(root,"analysis/common/html_fragment.py"),c("--input",native,"--output",fragment),python)
 if(!identical(hashes,unname(tools::md5sum(c(input,facilities)))))stop("Source inputs changed")
 list(native=native,fragment=fragment,data_dir=data)
}
if(sys.nframe()==0L){
 args<-commandArgs(trailingOnly=TRUE)
 value<-function(k,default=""){i<-match(k,args);if(is.na(i))return(default);if(i==length(args))stop("Supply ",k);args[i+1L]}
 script<-gsub("~+~"," ",sub("^--file=","",grep("^--file=",commandArgs(),value=TRUE)[1]),fixed=TRUE)
 root<-normalizePath(file.path(dirname(script),"..","..",".."),mustWork=TRUE)
 if(!nzchar(value("--join-dir")) && !nzchar(value("--input-zip",Sys.getenv("SURGO_MANITOBA_INPUT_ZIP",""))))stop("Supply --join-dir or --input-zip")
 pandoc<-value("--pandoc-dir",Sys.getenv("RSTUDIO_PANDOC",""));if(nzchar(pandoc))Sys.setenv(RSTUDIO_PANDOC=pandoc)
 report<-build_lagos_aggregate(root,value("--join-dir"),value("--cache-dir","data/cache"),value("--work-dir","output/aggregate_reports/lagos"),value("--python","python3"),value("--input-zip",Sys.getenv("SURGO_MANITOBA_INPUT_ZIP","")))
 output<-value("--output-dir","reports");if(!grepl("^/|^[A-Za-z]:",output))output<-file.path(root,output)
 dir.create(output,recursive=TRUE,showWarnings=FALSE)
 rmarkdown::render(file.path(root,"administrative_area/analysis/lagos/Lagos_analysis_aggregate.Rmd"),output_file="Lagos_analysis_aggregate.html",output_dir=normalizePath(output),params=list(prepared_fragment=report$fragment),quiet=TRUE,envir=new.env(parent=globalenv()))
 source(file.path(root,"administrative_area/analysis/report_pipeline.R"))
 run_stage(file.path(root,"administrative_area/analysis/lagos/verify_html.py"),c("--data-dir",report$data_dir,"--html",file.path(output,"Lagos_analysis_aggregate.html")),value("--python","python3"))
 cat("Saved Lagos_analysis_aggregate.html\n")
}
